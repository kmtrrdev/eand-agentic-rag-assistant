from typing import Any, Dict
from app.guardrails.security_utils import is_arabic_text


def safe_response_node(state: Dict[str, Any]) -> Dict[str, Any]:
    question = state.get("question", "")
    is_ar = is_arabic_text(question)

    guardrail_result = state.get("guardrail_result") or {}
    if not guardrail_result.get("allowed", True):
        safe_msg = guardrail_result.get("safe_message") or (
            "عذراً، لا يمكن معالجة هذا الطلب لأسباب أمنية."
            if is_ar
            else "This request cannot be processed for security reasons."
        )
        step_info = {
            "node": "safe_response",
            "title_ar": "الرد الأمني المباشر",
            "title_en": "Security Guardrail Response",
            "status": "blocked",
            "badge": "🛡️ حظر أمني",
            "description_ar": "تم توجيه الرد من خلال حارس الأمان المباشر.",
            "description_en": "Direct response generated by security guardrail.",
            "details": {"reason": "security_violation"},
        }
        return {
            "answer": safe_msg,
            "confidence": 1.0,
            "sources": [],
            "documents": [],
            "context": "",
            "workflow_trace": [step_info],
        }

    needs_clarification = state.get("needs_clarification", False)
    if needs_clarification:
        hint = state.get("clarification_hint")
        if hint:
            msg = hint
        elif is_ar:
            msg = "باقات اتصالات مصر للأفراد بتشمل باقات حكاية مكسات (مكالمات وإنترنت) وباقات حكاية إنترنت وباقات إمرالد الشهرية. قولي ميزانيتك الشهرية أو استخدامك المفضل وأرشحلك الأنسب فوراً!"
        else:
            msg = "e& Egypt consumer plans include Hekaya Mixat, Hekaya Internet, and Emerald. Please let me know your monthly budget or preferred usage so I can recommend the best plan!"

        step_info = {
            "node": "safe_response",
            "title_ar": "الاستفسار التوضيحي",
            "title_en": "Needs Clarification",
            "status": "completed",
            "badge": "ℹ️ استفسار توضيحي",
            "description_ar": "طلب توضيح لتحديد النظام الأنسب للعميل.",
            "description_en": "Clarification prompt to determine the best plan track.",
            "details": {"reason": "needs_clarification"},
        }
        return {
            "answer": msg,
            "confidence": 1.0,
            "sources": [],
            "documents": [],
            "context": "",
            "workflow_trace": [step_info],
        }

    is_out_of_scope = state.get("is_out_of_scope", False)
    if is_out_of_scope:
        if is_ar:
            msg = (
                "أهلاً بك! أنا المساعد الذكي المخصص لخدمات وباقات اتصالات مصر (e& Egypt). "
                "أنا هنا لمساعدتك في الاستفسار عن باقات الإنترنت والمكالمات والأنظمة المتاحة للأفراد. "
                "كيف يمكنني مساعدتك في باقاتنا اليوم؟"
            )
        else:
            msg = (
                "Hello! I am the e& Egypt smart telecom assistant. "
                "I specialize in answering inquiries about e& Egypt mobile, internet, and consumer packages. "
                "How may I assist you with our telecom services today?"
            )
        step_info = {
            "node": "safe_response",
            "title_ar": "توجيه نطاق الاختصاص",
            "title_en": "Out-of-Scope Redirection",
            "status": "completed",
            "badge": "🧭 توجيه النطاق",
            "description_ar": "توجيه المستخدم بلباقة لأنظمة وباقات اتصالات مصر للأفراد.",
            "description_en": "Politely redirected user to e& Egypt consumer telecom topics.",
            "details": {"reason": "out_of_scope_query"},
        }
        return {
            "answer": msg,
            "confidence": 1.0,
            "sources": [],
            "documents": [],
            "context": "",
            "workflow_trace": [step_info],
        }

    is_unsupported_service = state.get("is_unsupported_service", False)
    if is_unsupported_service:
        if is_ar:
            msg = (
                "أهلاً بك! تفاصيل هذا النظام (مثل خطوط وحسابات الشركات، أو إجراءات التحويل الإدارية، أو نزاعات الفواتير) "
                "غير متوفرة في قاعدة بيانات باقات الأفراد الحالية. "
                "للحصول على المساعدة الدقيقة، يمكنك التواصل مباشرة مع خدمة عملاء اتصالات مصر عبر الاتصال بـ 111 أو 16511، "
                "أو زيارة أقرب فرع. "
                "ويسعدني دائماً مساعدتك في اختيار أي باقة من باقات الأفراد (حكاية، إمرالد، باقات الكارت، إنترنت)!"
            )
        else:
            msg = (
                "Hello! Details regarding enterprise/corporate lines, administrative transfers, or billing dispute procedures "
                "are outside our consumer plans knowledge base. "
                "For assistance with corporate services or account management, please contact e& Egypt customer support at 111 (or 16511) "
                "or visit your nearest e& store. "
                "I am gladly here to assist you with any consumer mobile or internet packages (Hekaya, Emerald, Prepaid)!"
            )
        step_info = {
            "node": "safe_response",
            "title_ar": "توجيه خدمة العملاء",
            "title_en": "Unsupported Service Referral",
            "status": "completed",
            "badge": "📞 توجيه لخدمة العملاء",
            "description_ar": "إرشاد العميل للقنوات الرسمية والخط الساخن 111 للخدمات الإدارية وحسابات الشركات.",
            "description_en": "Referred user to official hotline 111 for administrative/enterprise requests.",
            "details": {"reason": "unsupported_service"},
        }
        return {
            "answer": msg,
            "confidence": 1.0,
            "sources": [],
            "documents": [],
            "context": "",
            "workflow_trace": [step_info],
        }

    if is_ar:
        msg = "عذراً، لم أتمكن من العثور على معلومات كافية للإجابة على استفسارك. هل يمكنك توضيح السؤال بشكل أدق؟"
    else:
        msg = "I could not find sufficient information to answer your inquiry. Could you please clarify your question?"

    step_info = {
        "node": "safe_response",
        "title_ar": "الرد الاحتياطي الآمن",
        "title_en": "Fallback Safe Response",
        "status": "completed",
        "badge": "ℹ️ استفسار توضيحي",
        "description_ar": "طلب توضيح إضافي عند عدم كفاية التفاصيل في قاعدة المعرفة.",
        "description_en": "Requested clarification from user due to limited KB context.",
        "details": {"reason": "insufficient_kb_context"},
    }

    return {
        "answer": msg,
        "confidence": 0.5,
        "sources": [],
        "documents": [],
        "context": "",
        "workflow_trace": [step_info],
    }
